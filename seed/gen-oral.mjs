const bad = [];
const seen = new Set();
for (const r of rows) {
  if (seen.has(r.code)) bad.push([r.code, 'コードが重複']);
  seen.add(r.code);
  if (!r.mustCover.length) bad.push([r.code, '要点なし']);
  if (!r.forbid.length) bad.push([r.code, '禁止事項なし']);
  if (!r.modelAnswer) bad.push([r.code, '模範解答なし']);
  // ハングルだけを見る。範囲を広く取ると漢字・かなまで引っかかる。
  if (/[\uAC00-\uD7A3\u1100-\u11FF\u3130-\u318F]/.test(JSON.stringify(r))) bad.push([r.code, 'ハングルが混入']);
}
const phases = {};
rows.forEach(r => { phases[r.phase] = (phases[r.phase] || 0) + 1; });
for (const [p, n] of Object.entries(phases)) if (n < 2) bad.push([p, '1局面に2問以上必要（毎回同じ問題になる）']);
if (bad.length) { console.error('不備:', bad); process.exit(1); }

writeFileSync(new URL('./oral.json', import.meta.url), JSON.stringify(rows, null, 2) + '\n');
console.log(`口頭試問 ${rows.length}問 → ${JSON.stringify(phases)}`);
