const file = new URL('./training-seed.json', import.meta.url);
const qs = JSON.parse(readFileSync(file, 'utf8'));
let n = 0;
for (const q of qs) {
  const t = TALK[q.code];
  if (!t) continue;
  if ((q.talk_example || '').trim()) continue;   // 既にあるものは触らない
  q.talk_example = t; n++;
}
writeFileSync(file, JSON.stringify(qs, null, 2) + '\n');
const law = qs.filter(q => q.test_type === 'law');
const has = law.filter(q => (q.talk_example || '').trim()).length;
console.log(`トーク例を${n}問に追加。特商法 ${has}/${law.length}問にトーク例あり`);
