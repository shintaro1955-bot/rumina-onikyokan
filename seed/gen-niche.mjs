const file = new URL('./training-seed.json', import.meta.url);
const cur = JSON.parse(readFileSync(file, 'utf8'));
const have = new Set(cur.map(q => q.code));
const add = [...sharp, ...kita, ...comp, ...kujo, ...genkan].filter(q => !have.has(q.code));

const bad = [];
for (const q of add) {
  if (!Array.isArray(q.choices) || q.choices.length !== 4) bad.push([q.code, '選択肢が4つでない']);
  if (new Set(q.choices).size !== q.choices.length) bad.push([q.code, '選択肢が重複']);
  if (!(q.answer_index >= 0 && q.answer_index < q.choices.length)) bad.push([q.code, '正解indexが範囲外']);
  if (!q.explanation) bad.push([q.code, '解説なし']);
  if (!q.source_note) bad.push([q.code, '出典なし']);
}
if (bad.length) { console.error('不備:', bad); process.exit(1); }

writeFileSync(file, JSON.stringify([...cur, ...add], null, 2) + '\n');
console.log(`追記 ${add.length}問 → 合計 ${cur.length + add.length}問`);
