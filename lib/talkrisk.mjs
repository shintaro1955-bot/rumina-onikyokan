/** 1本ぶんのテキストを走査。見つかった言い回しをそのまま引用して返す。 */
export function scanText(text) {
  const t = String(text || '');
  const hits = [];
  for (const r of RULES) {
    const m = t.match(r.re);
    if (!m) continue;
    // 前後を少し含めて引用（どこで言ったか分かるように）
    const i = Math.max(0, m.index - 18);
    const quote = t.slice(i, Math.min(t.length, m.index + m[0].length + 22)).replace(/\s+/g, ' ').trim();
    hits.push({ id: r.id, level: r.level, law: r.law, label: r.label, why: r.why, instead: r.instead, matched: m[0], quote });
  }
  return hits;
}

/**
 * 1日ぶん（pings）を走査してまとめる。
 * 同じ型は件数でまとめ、代表の引用を1つ持つ（同じ指摘を何度も並べない）。
 */
export function scanPings(pings = []) {
  const byId = new Map();
  for (const p of pings) {
    for (const h of scanText(p.text)) {
      const cur = byId.get(h.id);
      if (cur) { cur.count++; if (cur.quotes.length < 3) cur.quotes.push(h.quote); }
      else byId.set(h.id, { ...h, count: 1, quotes: [h.quote], quote: undefined });
    }
  }
  const items = [...byId.values()].sort((a, b) => (a.level === b.level) ? b.count - a.count : (a.level === 'high' ? -1 : 1));
  return { items, high: items.filter(x => x.level === 'high').length, mid: items.filter(x => x.level === 'mid').length };
}
